"""Creates (or resets) the single dedicated admin login and writes its
credentials to backend/admin-creds.txt (gitignored — never commit it).

There's no "forgot password" email flow in this app (no SMTP configured),
so this script is the reset mechanism: re-run it any time to rotate the
admin password. It also makes sure the account's email is present in
ADMIN_EMAILS in backend/.env, since that's what actually grants admin
access (see src/config.py) — the DB row alone isn't enough.

Usage (from backend/, with the venv active):
    python scripts/reset_admin_password.py
    python scripts/reset_admin_password.py --email admin@example.com
"""
import argparse
import os
import re
import secrets
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app import create_app
from src.config import DevConfig
from src.extensions import db
from src.models import User

DEFAULT_EMAIL = "admin@ayodhyaai.local"
ENV_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), ".env")
CREDS_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "admin-creds.txt")


def _ensure_admin_email_in_env(email: str) -> None:
    """Appends `email` to ADMIN_EMAILS in backend/.env if it's not already
    there (creating the line, or the file, if needed) — matching-but-not-
    duplicating so re-running this script is safe.
    """
    lines = []
    if os.path.exists(ENV_PATH):
        with open(ENV_PATH, "r") as f:
            lines = f.readlines()

    for i, line in enumerate(lines):
        m = re.match(r"^ADMIN_EMAILS=(.*)$", line.rstrip("\n"))
        if m:
            current = [e.strip() for e in m.group(1).split(",") if e.strip()]
            if email.lower() not in (e.lower() for e in current):
                current.append(email)
            lines[i] = f"ADMIN_EMAILS={','.join(current)}\n"
            break
    else:
        lines.append(f"\nADMIN_EMAILS={email}\n")

    with open(ENV_PATH, "w") as f:
        f.writelines(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--email", default=DEFAULT_EMAIL, help=f"Admin login email (default: {DEFAULT_EMAIL})")
    parser.add_argument("--name", default="Admin", help="Display name for the account (default: Admin)")
    args = parser.parse_args()

    password = secrets.token_urlsafe(15)

    app = create_app(DevConfig)
    with app.app_context():
        user = User.query.filter_by(email=args.email).first()
        if user is None:
            user = User(email=args.email, name=args.name, provider="local")
            db.session.add(user)
        user.set_password(password)
        db.session.commit()

    _ensure_admin_email_in_env(args.email)

    with open(CREDS_PATH, "w") as f:
        f.write(
            "Grantha admin login — generated by scripts/reset_admin_password.py\n"
            "Do not commit this file (it's in .gitignore). Re-run the script to rotate the password.\n\n"
            f"Email:    {args.email}\n"
            f"Password: {password}\n"
        )
    os.chmod(CREDS_PATH, 0o600)

    print(f"Admin account ready: {args.email}")
    print(f"Credentials written to {CREDS_PATH} (chmod 600, gitignored).")
    print("ADMIN_EMAILS in .env updated — restart the backend for it to take effect.")


if __name__ == "__main__":
    main()
